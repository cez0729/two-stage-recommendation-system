"""Paired comparison of frozen mean and GRU encoders; no test-set tuning."""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd
import torch
from scipy.stats import binomtest

from recsys.evaluation.metrics import bootstrap_mean_ci
from recsys.utils.io import write_json


def main() -> None:
    root = Path("results/video_games_2018/sequence")
    frames = {
        name: pd.read_parquet(root / f"{name}_final_per_user/test.parquet")
        for name in ("mean", "gru")
    }
    paired = frames["mean"].merge(
        frames["gru"], on=["user_idx", "target_item_idx"],
        suffixes=("_mean", "_gru"), validate="one_to_one",
    )
    if len(paired) != len(frames["mean"]) or len(paired) != len(frames["gru"]):
        raise ValueError("Models were not evaluated on identical queries")
    comparisons = {}
    for metric in ("recall@10", "recall@100", "ndcg@10"):
        delta = paired[f"{metric}_gru"] - paired[f"{metric}_mean"]
        low, high = bootstrap_mean_ci(delta.tolist(), samples=2000, seed=42)
        comparisons[metric] = {
            "mean": float(paired[f"{metric}_mean"].mean()),
            "gru": float(paired[f"{metric}_gru"].mean()),
            "gru_minus_mean": float(delta.mean()),
            "paired_bootstrap_ci95": {"low": low, "high": high},
        }
        if metric.startswith("recall"):
            wins = int((delta > 0).sum())
            losses = int((delta < 0).sum())
            comparisons[metric].update(
                gru_only_hits=wins, mean_only_hits=losses,
                exact_mcnemar_p=(float(binomtest(wins, wins + losses).pvalue)
                                 if wins + losses else 1.0),
            )
    models = {}
    checkpoint_names = {"mean": "two_tower_mean_comparison", "gru": "two_tower_gru_logq"}
    validation_paths = {
        "mean": root / "mean_validation_metrics.json",
        "gru": Path("results/video_games_2018/tuning/two_tower_gru_logq_metrics.json"),
    }
    for name in ("mean", "gru"):
        validation = json.loads(validation_paths[name].read_text())
        final = json.loads((root / f"{name}_final_metrics.json").read_text())
        checkpoint = torch.load(
            f"models/video_games_2018/{checkpoint_names[name]}.pt",
            map_location="cpu", weights_only=False,
        )
        # Checkpoints are locally generated by this experiment.
        state = checkpoint["model_state_dict"]
        models[name] = {
            "parameters": sum(t.numel() for t in state.values()),
            "best_epoch": final["best_epoch"],
            "epochs_run": len(validation["training_history"]),
            "observed_epoch_seconds_sum": sum(
                row["epoch_seconds"] for row in validation["training_history"]
            ),
            "test_coverage@10": final["splits"]["test"]["metrics"]["coverage@10"],
            "test_popularity_bias_ratio": final["splits"]["test"]["metrics"][
                "popularity_bias_ratio"
            ],
        }
    primary = comparisons["recall@100"]["paired_bootstrap_ci95"]
    payload = {
        "seed": 42, "users": len(paired), "bootstrap_samples": 2000,
        "primary_endpoint": "test recall@100, GRU minus mean",
        "protocol": "Identical Video Games splits and hyperparameters; validation early stopping",
        "scope": "GRU history encoder within Two-Tower, not an exact GRU4Rec reproduction",
        "comparisons": comparisons, "models": models,
        "acceptance": {
            "primary_ci_strictly_positive": bool(primary["low"] > 0),
            "primary_ci_strictly_negative": bool(primary["high"] < 0),
            "promote_serving_model": False,
        },
        "limitations": [
            "Single-seed architecture comparison; paired user uncertainty is not seed uncertainty",
            "Concurrent training workloads make observed epoch times unsuitable for speed claims",
            "Prior Video Games test exploration means this is not a new untouched benchmark",
            "More GRU parameters confound architecture with capacity; no parameter-matched control",
            "Other endpoints are exploratory; no multiplicity-adjusted significance claim",
        ],
    }
    write_json(root / "paired_comparison.json", payload)
    print(json.dumps(payload, indent=2))


if __name__ == "__main__":
    main()
